#!/usr/bin/env node
// Generates .github/workflows/ci.yml from scripts/ci-matrix.json. There is no YAML dependency:
// renderCi is a pure, deterministic string builder so check-ci can compare byte for byte.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(HERE, '..')
const HEADER = '# generated by scripts/gen-ci.mjs from scripts/ci-matrix.json - do not edit'
const WORKFLOW_PATH = path.join('.github', 'workflows', 'ci.yml')

export function renderCi(matrix) {
  const resultsDir = matrix.results_dir
  const lines = []

  lines.push(HEADER)
  lines.push('name: ci')
  lines.push('on: [push, pull_request]')
  lines.push('permissions:')
  lines.push('  contents: read')
  lines.push('jobs:')
  lines.push('  check:')
  lines.push('    strategy:')
  lines.push('      fail-fast: false')
  lines.push('      matrix:')
  lines.push('        include:')
  for (const os of matrix.os) {
    for (const node of matrix.node) {
      lines.push(`          - name: ${os.name}`)
      lines.push(`            runs_on: ${os.runs_on}`)
      lines.push(`            node: ${node}`)
    }
  }
  lines.push('    runs-on: ${{ matrix.runs_on }}')
  lines.push('    env:')
  lines.push(`      CLIWORKER_RESULTS_DIR: \${{ github.workspace }}/${resultsDir}`)
  lines.push('    steps:')
  lines.push('      - uses: actions/checkout@v4')
  lines.push('      - uses: actions/setup-node@v4')
  lines.push('        with:')
  lines.push('          node-version: ${{ matrix.node }}')
  lines.push('      - run: npm ci')
  lines.push(`      - run: ${matrix.check_command}`)
  lines.push('      - uses: actions/upload-artifact@v4')
  lines.push('        if: always()')
  lines.push('        with:')
  lines.push('          name: test-results-${{ matrix.name }}-node${{ matrix.node }}')
  lines.push('          path: |')
  for (const artifact of matrix.artifacts) {
    lines.push(`            ${resultsDir}/${artifact}`)
  }
  lines.push('          if-no-files-found: warn')
  lines.push('  perf:')
  lines.push(`    runs-on: ${matrix.perf.runs_on}`)
  lines.push('    continue-on-error: true')
  lines.push('    steps:')
  lines.push('      - uses: actions/checkout@v4')
  lines.push('      - uses: actions/setup-node@v4')
  lines.push('        with:')
  lines.push(`          node-version: ${matrix.perf.node}`)
  lines.push('      - run: npm ci')
  lines.push(`      - run: ${matrix.perf.command}`)

  return `${lines.join('\n')}\n`
}

function main() {
  const args = process.argv.slice(2)
  let root = REPO_ROOT
  let toStdout = false

  for (let i = 0; i < args.length; i += 1) {
    const flag = args[i]
    if (flag === '--stdout') {
      toStdout = true
    } else if (flag === '--root') {
      const value = args[i + 1]
      if (typeof value !== 'string' || value === '') {
        process.stderr.write('--root requires a directory\n')
        process.exitCode = 2
        return
      }
      root = path.resolve(value)
      i += 1
    } else {
      process.stderr.write(`unknown argument: ${flag}\nusage: node scripts/gen-ci.mjs [--root <dir>] [--stdout]\n`)
      process.exitCode = 2
      return
    }
  }

  const matrixFile = path.join(root, 'scripts', 'ci-matrix.json')
  let matrix
  try {
    matrix = JSON.parse(fs.readFileSync(matrixFile, 'utf8'))
  } catch {
    process.stderr.write(`gen-ci: cannot read ${matrixFile}\n`)
    process.exitCode = 2
    return
  }

  const text = renderCi(matrix)
  if (toStdout) {
    process.stdout.write(text)
    return
  }

  const target = path.join(root, WORKFLOW_PATH)
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, text)
  process.stdout.write(`gen-ci: wrote ${WORKFLOW_PATH.split(path.sep).join('/')}\n`)
}

const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()

if (invokedDirectly) main()
